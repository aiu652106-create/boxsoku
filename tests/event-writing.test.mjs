import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { parseSourceHtml } from '../functions/_shared/event-sources.js';
import { buildEventWritingPacket } from '../functions/_shared/event-writing.js';
import { collectCards } from '../scripts/collect-event-cards.mjs';

const html = await fs.readFile(new URL('./fixtures/lemino-pxb-real-minimal.html', import.meta.url), 'utf8');
const mobile = await fs.readFile(new URL('./fixtures/boxing-mobile-real-minimal.html', import.meta.url), 'utf8');
const discovery = parseSourceHtml('boxing-mobile', mobile, { sourceUrl: 'https://boxmob.jp/sp/schedule.html' });
assert.equal(discovery.extractedCount, 1);
assert.equal(discovery.events[0].event.discovery_date_label, '10/29');
assert.equal(discovery.events[0].event.event_date, '');
assert.equal(discovery.events[0].event.bouts.length, 0);
assert.ok(discovery.events[0].validationErrors.includes('year_not_explicit'));
const options = { sourceUrl: 'https://lemino.docomo.ne.jp/ft/0000002/pxb/' };
const parsed = parseSourceHtml('lemino', html, options);
assert.equal(parsed.extractedCount, 2);
const [past, upcoming] = parsed.events.map(x => x.event);
assert.equal(past.event_date, '2026-09-08');
assert.equal(upcoming.event_date, '2026-09-21');
assert.equal(upcoming.venue, 'たま未来メッセ(八王子市)');
assert.equal(upcoming.bouts[0].fighter_a_name, 'セムジュ・デビッド');
assert.equal(upcoming.bouts[0].fighter_b_name, '佐々木 尽');
assert.equal(upcoming.bouts[0].bout_number, 6);
assert.equal(upcoming.bouts[0].rounds, 10);
assert.equal(upcoming.broadcast_start_time, '13:00:00');
assert.equal(upcoming.source_event_key, options.sourceUrl + '#pb161');
assert.equal(parsed.events[1].validationErrors.length, 0);
assert.equal(parseSourceHtml('lemino', `<!--${html.replace(/<!--[\s\S]*?-->/g, '')}-->`, options).extractedCount, 0);
const now = new Date('2026-09-12T00:00:00Z');
assert.equal(buildEventWritingPacket(past, { now }).can_prepare_draft, false);
const packet = buildEventWritingPacket(upcoming, { now });
assert.equal(packet.can_prepare_draft, true);
assert.equal(packet.publication_ready, false);
assert.equal(packet.draft.status, 'draft');
assert.equal(packet.draft.isAdvertorial, false);
assert.equal(packet.draft.image, '');
assert.equal(packet.draft.affiliateLinks.length, 0);
assert.match(packet.writer_instructions, /BoxRec/);
assert.equal(buildEventWritingPacket({ ...upcoming, source_kind: 'discovery' }, { now }).can_prepare_draft, false);
const malformed = parseSourceHtml('lemino', html.replace('<p class="name">佐々木 尽</p>', ''), options);
assert.ok(malformed.events[1].validationErrors.includes('ambiguous_card_row'));
const unordered = parseSourceHtml('lemino', html.replaceAll('＜第6試合＞', ''), options).events[1].event;
assert.equal(unordered.bouts[0].bout_number, null);
assert.match(buildEventWritingPacket(unordered, { now }).draft.body, /試合順は未確認/);
const report = await collectCards({ readCached: async () => html, now });
assert.equal(report.sources[0].requests, 0);
assert.equal(report.packets.filter(p => p.can_prepare_draft).length, 1);
for (const status of [403,429,503]) {
  let calls = 0;
  const result = await collectCards({ fetchImpl: async () => { calls++; return new Response('', { status }); }, now });
  assert.equal(calls, 1);
  assert.equal(result.sources[0].outcome, 'blocked');
  assert.equal(result.packets.length, 0);
}
console.log('Real fight-card and writing packet tests passed');
